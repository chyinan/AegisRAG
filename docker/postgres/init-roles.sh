#!/bin/sh
set -eu

until pg_isready -h "$DB_HOST" -U "$POSTGRES_USER" -d "$POSTGRES_DB"; do
  sleep 1
done

export PGPASSWORD="$POSTGRES_PASSWORD"

migration_exists=$(psql -h "$DB_HOST" -U "$POSTGRES_USER" -d "$POSTGRES_DB" -tAc "SELECT 1 FROM pg_roles WHERE rolname = '$POSTGRES_MIGRATION_USER'")
if [ -z "$migration_exists" ]; then
  psql -h "$DB_HOST" -U "$POSTGRES_USER" -d "$POSTGRES_DB" -v ON_ERROR_STOP=1 -c "CREATE ROLE $POSTGRES_MIGRATION_USER LOGIN PASSWORD '$POSTGRES_MIGRATION_PASSWORD' CREATEDB"
else
  psql -h "$DB_HOST" -U "$POSTGRES_USER" -d "$POSTGRES_DB" -v ON_ERROR_STOP=1 -c "ALTER ROLE $POSTGRES_MIGRATION_USER WITH LOGIN PASSWORD '$POSTGRES_MIGRATION_PASSWORD' CREATEDB"
fi

psql -h "$DB_HOST" -U "$POSTGRES_USER" -d "$POSTGRES_DB" -v ON_ERROR_STOP=1 \
  -c "CREATE EXTENSION IF NOT EXISTS vector" \
  -c "GRANT USAGE, CREATE ON SCHEMA public TO $POSTGRES_MIGRATION_USER" \
  -c "GRANT USAGE, CREATE ON SCHEMA public TO $POSTGRES_RUNTIME_USER"

runtime_exists=$(psql -h "$DB_HOST" -U "$POSTGRES_USER" -d "$POSTGRES_DB" -tAc "SELECT 1 FROM pg_roles WHERE rolname = '$POSTGRES_RUNTIME_USER'")
if [ -z "$runtime_exists" ]; then
  psql -h "$DB_HOST" -U "$POSTGRES_USER" -d "$POSTGRES_DB" -v ON_ERROR_STOP=1 -c "CREATE ROLE $POSTGRES_RUNTIME_USER LOGIN PASSWORD '$POSTGRES_RUNTIME_PASSWORD'"
else
  psql -h "$DB_HOST" -U "$POSTGRES_USER" -d "$POSTGRES_DB" -v ON_ERROR_STOP=1 -c "ALTER ROLE $POSTGRES_RUNTIME_USER WITH LOGIN PASSWORD '$POSTGRES_RUNTIME_PASSWORD'"
fi
